// 自动生成边
function generateEdges(nodes) {
  const edges = [];
  let edgeIdx = 0;
  for (const node of nodes) {
    // 包含关系边：parentId → node
    if (node.parentId) {
      edges.push({
        _id: 'ke_' + (++edgeIdx),
        sourceId: node.parentId,
        targetId: node._id,
        type: 'contains',
        courseId: node.courseId
      });
    } else {
      // depth 0 节点：kpId → node（知识点到子知识点的包含关系）
      edges.push({
        _id: 'ke_' + (++edgeIdx),
        sourceId: node.kpId,
        targetId: node._id,
        type: 'contains',
        courseId: node.courseId
      });
    }
    // 前置依赖边：prerequisites → node
    if (node.prerequisites && node.prerequisites.length > 0) {
      for (const prereq of node.prerequisites) {
        edges.push({
          _id: 'ke_' + (++edgeIdx),
          sourceId: prereq,
          targetId: node._id,
          type: 'prerequisite',
          courseId: node.courseId
        });
      }
    }
  }
  return edges;
}

